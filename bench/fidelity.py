"""Fidelity and token benchmark: Quillwork against python-docx on the public corpus.

    pip install python-docx tiktoken        # plus the quillwork wheel (or `maturin develop`)
    python bench/fidelity.py [--json OUT.json] [FILE.docx ...]

With no files it runs every .docx in corpus/synthetic and corpus/fixtures (all generated by the
scripts in corpus/, nothing private). For each file it measures:

no-op     open and save without changes.
          file: is the whole output byte-identical to the input?
          entries: zip entries whose stored bytes (local header + compressed data) are unchanged.
          parts: entries whose *decompressed* content is unchanged (ignores re-compression).
edit      replace one word that occurs once in the body (the first such word of at least four
          letters in a body paragraph's first run) with "Edited".
          Quillwork writes it as a tracked change; python-docx has no tracked-change API, so it
          overwrites the run text. That favours python-docx on size, not on locality.
          other entries: zip entries other than word/document.xml whose content changed.
          paragraphs changed: outermost w:p elements in word/document.xml whose bytes differ
          from the input (1 is the minimum: the edited paragraph).
tokens    o200k_base tokens (tiktoken, a stand-in for any LLM tokenizer) of: Quillwork's
          full projection (`Document.read(budget=...)` large enough for the whole document, with
          anchors; a default `read()` returns a budgeted first page instead), python-docx's plain paragraph text (no
          anchors, no tables, no formatting) and the raw word/document.xml.
"""

from __future__ import annotations

import argparse
import io
import json
import platform
import re
import sys
import zipfile
from pathlib import Path
from typing import Any

import docx
import quillwork
import tiktoken

ROOT = Path(__file__).resolve().parents[1]
ENC = tiktoken.get_encoding("o200k_base")
MAIN = "word/document.xml"
WORD = re.compile(r"[A-Za-z]{4,}")
FULL = 10**9


def raw_entries(data: bytes) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for info in z.infolist():
            start = info.header_offset
            name_len = int.from_bytes(data[start + 26 : start + 28], "little")
            extra_len = int.from_bytes(data[start + 28 : start + 30], "little")
            out[info.filename] = data[
                start : start + 30 + name_len + extra_len + info.compress_size
            ]
    return out


def parts(data: bytes) -> dict[str, bytes]:
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return {n: z.read(n) for n in z.namelist()}


def paragraphs(xml: bytes) -> list[bytes]:
    """Outermost <w:p>...</w:p> spans, in order (nested paragraphs, e.g. in text boxes, stay inside)."""
    out: list[bytes] = []
    depth, start = 0, 0
    for m in re.finditer(rb"<w:p(?=[\s>/])[^>]*?(/?)>|</w:p>", xml):
        if m.group(0).startswith(b"</"):
            depth -= 1
            if depth == 0:
                out.append(xml[start : m.end()])
        elif m.group(1) == b"/":
            if depth == 0:
                out.append(m.group(0))
        else:
            if depth == 0:
                start = m.start()
            depth += 1
    return out


def noop(before: bytes, after: bytes) -> dict[str, Any]:
    a, b = raw_entries(before), raw_entries(after)
    pa, pb = parts(before), parts(after)
    return {
        "file_identical": before == after,
        "entries_identical": sum(1 for n in a if b.get(n) == a[n]),
        "parts_identical": sum(1 for n in pa if pb.get(n) == pa[n]),
        "entries": len(a),
    }


def edit_locality(before: bytes, after: bytes) -> dict[str, Any]:
    pa, pb = parts(before), parts(after)
    other = sorted(n for n in set(pa) | set(pb) if n != MAIN and pa.get(n) != pb.get(n))
    old, new = paragraphs(pa[MAIN]), paragraphs(pb[MAIN])
    changed = (
        [i for i, (x, y) in enumerate(zip(old, new)) if x != y]
        if len(old) == len(new)
        else None
    )
    return {
        "other_entries_changed": other,
        "paragraphs_changed": changed,
        "paragraphs": len(old),
    }


def pick_word(path: Path) -> str | None:
    """A word of 4+ letters from the first run of a body paragraph, whose first occurrence in the
    document text is that run (so "replace the first occurrence" hits the same spot in both tools).
    Tables are counted too, since Quillwork's search covers them."""
    d = docx.Document(str(path))
    seen: set[str] = set()
    for block in d.element.body.iter(docx.oxml.ns.qn("w:p")):
        p = docx.text.paragraph.Paragraph(block, d)
        runs = p.runs
        if runs and block.getparent() is d.element.body:
            for w in WORD.findall(runs[0].text):
                if w not in seen and len(re.findall(rf"\b{w}\b", p.text)) == 1:
                    return w
        seen.update(re.findall(r"\w+", p.text))
    return None


def bench_file(path: Path) -> dict[str, Any]:
    data = path.read_bytes()
    row: dict[str, Any] = {
        "file": str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else path.name
    }

    q = quillwork.Document.open(data)
    row["quillwork_noop"] = noop(data, q.save())
    projection = q.read(budget=FULL)  # the whole document, not the first budgeted page
    row["tokens"] = {
        "quillwork_projection": len(ENC.encode(projection)),
        "document_xml": len(ENC.encode(parts(data)[MAIN].decode("utf-8", "replace"))),
    }

    d = docx.Document(io.BytesIO(data))
    buf = io.BytesIO()
    d.save(buf)
    row["python_docx_noop"] = noop(data, buf.getvalue())
    row["tokens"]["python_docx_text"] = len(
        ENC.encode("\n".join(p.text for p in d.paragraphs))
    )

    word = pick_word(path)
    row["edit_word_found"] = word is not None
    if word is not None:
        q = quillwork.Document.open(data)
        q.set_now(1_767_225_600)
        hit = re.search(
            r"^\[([0-9a-z.]+)", q.find(word), re.MULTILINE
        )  # first hit = the paragraph picked
        assert hit, word
        q.apply(
            {
                "base_version": q.version,
                "ops": [
                    {
                        "op": "replace_text",
                        "anchor": hit.group(1),
                        "find": word,
                        "replace": "Edited",
                    }
                ],
            }
        )
        row["quillwork_edit"] = edit_locality(data, q.save())

        d = docx.Document(io.BytesIO(data))
        for p in d.paragraphs:
            if p.runs and re.search(
                rf"\b{word}\b", p.runs[0].text
            ):  # the first such paragraph
                p.runs[0].text = re.sub(
                    rf"\b{word}\b", "Edited", p.runs[0].text, count=1
                )
                break
        buf = io.BytesIO()
        d.save(buf)
        row["python_docx_edit"] = edit_locality(data, buf.getvalue())
        # both tools must have edited the same paragraph, or the comparison is void
        row["same_target"] = row["quillwork_edit"]["paragraphs_changed"] == row[
            "python_docx_edit"
        ]["paragraphs_changed"] or (
            len(row["quillwork_edit"]["paragraphs_changed"] or []) >= 1
            and (row["quillwork_edit"]["paragraphs_changed"] or [None])[0]
            in (row["python_docx_edit"]["paragraphs_changed"] or [])
        )
    return row


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("files", nargs="*", type=Path)
    ap.add_argument("--json", type=Path)
    args = ap.parse_args(argv)
    files = args.files or sorted(
        (ROOT / "corpus" / "synthetic").glob("*.docx")
    ) + sorted((ROOT / "corpus" / "fixtures").glob("*.docx"))
    rows = [bench_file(p) for p in files]
    env = {
        "quillwork": quillwork.__version__,
        "python-docx": getattr(docx, "__version__", "?"),
        "tiktoken": tiktoken.__version__,
        "python": platform.python_version(),
    }
    if args.json:
        args.json.write_text(json.dumps({"env": env, "rows": rows}, indent=1) + "\n")

    print("versions: " + ", ".join(f"{k} {v}" for k, v in env.items()))
    print(
        "\n| file | no-op: Quillwork file / entries | no-op: python-docx file / entries / parts "
        "| edit: other entries changed (Q / pd) | edit: paragraphs changed (Q / pd) |"
    )
    print("|---|---|---|---|---|")
    yes = {True: "identical", False: "changed"}
    for r in rows:
        qn, pn = r["quillwork_noop"], r["python_docx_noop"]
        pd = f"{yes[pn['file_identical']]} / {pn['entries_identical']}/{pn['entries']} / {pn['parts_identical']}/{pn['entries']}"
        if r.get("edit_word_found"):
            qe, pe = r["quillwork_edit"], r["python_docx_edit"]
            other = f"{len(qe['other_entries_changed'])} / {len(pe['other_entries_changed'])}"
            n = qe["paragraphs"]
            paras = f"{len(qe['paragraphs_changed'])}/{n} / {len(pe['paragraphs_changed'])}/{n}"
            if not r["same_target"]:
                paras += " (different targets)"
        else:
            other = paras = "n/a"
        print(
            f"| {Path(r['file']).name} | {yes[qn['file_identical']]} / {qn['entries_identical']}/{qn['entries']} | {pd} | {other} | {paras} |"
        )

    print(
        "\n| file | tokens: Quillwork projection | tokens: python-docx plain text | tokens: raw document.xml |"
    )
    print("|---|---|---|---|")
    for r in rows:
        t = r["tokens"]
        print(
            f"| {Path(r['file']).name} | {t['quillwork_projection']} | {t.get('python_docx_text', 'n/a')} | {t['document_xml']} |"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
